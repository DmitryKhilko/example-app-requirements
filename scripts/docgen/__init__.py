"""Генератор документации по метаданным спецификаций: «Обзор» реестра, индексы подразделов и модулей, меню, релизы, взаимосвязи.

Скрипт обходит папку docs/, читает YAML Front Matter у каждого .md-файла и
собирает иерархическое оглавление «Модуль -> Субмодуль -> Фича» со ссылками на
спецификации. Результат записывается в docs/registry/overview.md (страница «Обзор»),
в index.md подразделов «Действующие» и «Архив», в index.md модулей, в docs/releases.md
и в блок меню zensical.toml.

Структура docs/ (меню сайта: горизонтальное «Проект» | «Реестр требований» | «Релизы»)
-----------------------------------------------------------------------------------
    project/about.md, glossary.md, roadmap.md   вкладка «Проект» (файлы ведут вручную)
    registry/overview.md                        вкладка «Реестр требований» -> «Обзор» (формируется)
    registry/active/index.md  + <модуль>/       «Действующие»: индекс подраздела формируется
    registry/archive/index.md + <модуль>/       «Архив»: индекс подраздела формируется
    releases.md                                 вкладка «Релизы» (формируется)
    index.md                                    стартовая страница: переадресация на «О продукте»

Принципы работы
---------------
* Все страницы собираются каждый раз с нуля (идемпотентно): новая спецификация
  появляется в обзоре, удалённая исчезает, изменённый статус обновляется.
* Спецификацией считается файл, в метаданных которого есть хотя бы одно из полей
  `module`, `submodule`, `feature_name`. Остальные статьи (глоссарий, «О продукте»,
  Roadmap и т. п.) в обзор не попадают. Спецификации лежат только в
  docs/registry/active/<модуль>/ или docs/registry/archive/<модуль>/ (иначе — ошибка проверки).
* Архивная спецификация — файл внутри docs/registry/archive/ ИЛИ файл со статусом
  `archived`. На странице «Обзор» такие фичи выводятся в отдельном разделе «Архивные спецификации».
* Страница «Обзор» (`# Обзор спецификаций продукта {#overview}`): свёрнутый инфо-блок «Статусы спецификаций», плитки со статусами и
  числами (они же кнопки фильтра; сверху общий итог), строка отбора по названию с кнопкой «Сбросить», затем разделы
  «Действующие спецификации» `{#active-features}` и «Архивные спецификации» `{#archived-features}`. Списки спецификаций —
  вложенные сворачиваемые блоки «Модуль» → «Субмодуль» со статистикой по статусам.
* Индексы подразделов («Действующие», «Архив») устроены так же, но без разделов: заголовок первого уровня, инфо-блок,
  плитки, строка отбора и сразу список только своих спецификаций (в «Действующих» нет статуса «архив», в «Архиве» —
  только он). Индексы модулей (разделы «Статистика» и «Спецификации») показывают только свой модуль.
* Каждая ссылка ведёт на раздел «Описание» (`#article-overview`) и снабжена атрибутами
  `data-preview` (окно предпросмотра) и `data-status` (код статуса для фильтра на странице).
* В сформированных файлах нет даты и времени, поэтому без реальных изменений в
  спецификациях они не меняются и автокоммит не создаётся.
* Взаимосвязи фичей. В метаданных спецификации можно задать блок `relations` (типы связей —
  в RELATION_TYPES). На него ссылаются по имени файла без расширения (оно же — якорь заголовка
  первого уровня), поэтому при переносе файла из active/ в archive/ связи не ломаются. Скрипт описывает связь
  один раз (в спецификации-источнике), а обратные связи («используется в», «расширяется…»)
  вычисляет сам. В каждой спецификации сразу после раздела «Описание» он создаёт и обновляет раздел
  «Взаимосвязи» (`{#relations}`) — схему Mermaid и таблицу только для ЭТОЙ фичи и её прямых
  соседей (полная карта связей не строится). Раздел заключён в маркеры RELATIONS_BEGIN/RELATIONS_END:
  всё между ними пересобирается с нуля, вручную править не нужно. Если маркеров нет, раздел
  вставляется перед первым заголовком, следующим за «Описанием».
* Проверки связей (ошибка — сборка падает): неизвестная фича, связь на себя, неизвестный тип связи
  или поле, повторяющееся имя файла у двух спецификаций, цикл в `depends_on`. Предупреждение:
  действующая фича зависит от архивной или расширяет её, одна и та же связь указана дважды.
  Без реальных изменений метаданных разделы «Взаимосвязи» не меняются, автокоммит не создаётся.

Структура пакета
----------------
Работа идёт в четыре этапа, каждый — в своём модуле:

    reader.py      1. чтение: обход docs/, разбор метаданных каждого файла
    validate/      2. проверка: метаданные, связи, структура, настройки проекта (ничего не пишет)
    generate/      3. генерация: обзор, индексы, меню, релизы, значки, разделы «Взаимосвязи» -> план записи
    apply.py       4. применение: запись плана на диск или сверка при --check
    cli.py         аргументы командной строки и последовательность этапов

Общее: config.py (константы), models.py (модель данных), problems.py (ошибки и предупреждения),
textutils.py, ordering.py (порядок модулей и спецификаций), layout.py (раскладка по папкам),
markdown.py (разбор заголовков), template.py (правила проверки из шаблона спецификации).
Зависимости идут только сверху вниз, циклических импортов нет.
"""
