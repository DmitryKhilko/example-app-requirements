/* ==========================================================================
   scroll-top.js — переход по меню всегда открывает страницу с самого верха

   Проблема. Выбрав в горизонтальном меню раздел («Спецификации», «Архив спецификаций»)
   и затем нажав в боковом меню на модуль (например, «Каталог товаров»), читатель видел
   страницу index.md прокрученной до середины: при мгновенной навигации (navigation.instant)
   новое содержимое подставляется без перезагрузки и может сохранить прежнюю позицию прокрутки.

   Решение. Клик по ссылке в горизонтальном или боковом меню без якоря (#...) возвращает
   прокрутку в начало страницы. Сброс повторяется несколько раз с короткими паузами: он
   должен сработать уже после того, как тема подставит содержимое новой страницы.
   Ссылки с якорем (например, на раздел в содержании) не затрагиваются: к якорю тема
   прокручивает страницу сама.

   Обработчик повешен на весь документ (делегирование событий, как в tiles.js и
   status-filter.js), поэтому работает после любой мгновенной навигации.
   ========================================================================== */

(function () {
  "use strict";

  var DELAYS = [0, 60, 200, 500];   // мс после клика

  function toTop() {
    if (window.location.hash) return;   // у новой страницы есть якорь — прокрутка к нему не наша забота
    window.scrollTo(0, 0);
  }

  document.addEventListener("click", function (e) {
    if (e.defaultPrevented && !e.target.closest) return;
    var link = e.target.closest ? e.target.closest(".md-tabs a[href], .md-sidebar--primary a[href]") : null;
    if (!link) return;
    var url;
    try { url = new URL(link.href, window.location.href); } catch (err) { return; }
    if (url.origin !== window.location.origin || url.hash) return;
    DELAYS.forEach(function (ms) { window.setTimeout(toTop, ms); });
  }, true);
})();
